BEGIN;

CREATE TABLE teachers (
    teacher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    email VARCHAR(255) UNIQUE,
    phone_number VARCHAR(30),
    hire_date DATE
);

CREATE TABLE classes (
    class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name VARCHAR(10) NOT NULL,
    school_year VARCHAR(9) NOT NULL,
    class_teacher_id BIGINT
        REFERENCES teachers(teacher_id)
        ON DELETE SET NULL,

    CONSTRAINT uq_classes_name_year
        UNIQUE (class_name, school_year)
);

CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    birth_date DATE NOT NULL,
    class_id BIGINT NOT NULL
        REFERENCES classes(class_id)
        ON DELETE RESTRICT,
    enrollment_date DATE NOT NULL
);

CREATE TABLE subjects (
    subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE lessons (
    lesson_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL
        REFERENCES classes(class_id)
        ON DELETE RESTRICT,
    teacher_id BIGINT NOT NULL
        REFERENCES teachers(teacher_id)
        ON DELETE RESTRICT,
    subject_id BIGINT NOT NULL
        REFERENCES subjects(subject_id)
        ON DELETE RESTRICT,
    day_of_week VARCHAR(20) NOT NULL,
    lesson_number INT NOT NULL,
    room VARCHAR(20),

    CONSTRAINT uq_lessons_class_day_number
        UNIQUE (class_id, day_of_week, lesson_number)
);

CREATE TABLE grades (
    grade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES students(student_id)
        ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL
        REFERENCES lessons(lesson_id)
        ON DELETE CASCADE,
    grade_value SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE parents (
    parent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    email VARCHAR(255) UNIQUE,
    phone_number VARCHAR(30)
);

CREATE TABLE student_parents (
    student_id BIGINT NOT NULL
        REFERENCES students(student_id)
        ON DELETE CASCADE,
    parent_id BIGINT NOT NULL
        REFERENCES parents(parent_id)
        ON DELETE CASCADE,
    relationship VARCHAR(30) NOT NULL,

    PRIMARY KEY (student_id, parent_id)
);


CREATE INDEX idx_students_class_id
    ON students(class_id);

CREATE INDEX idx_lessons_class_day
    ON lessons(class_id, day_of_week);

CREATE INDEX idx_lessons_teacher_id
    ON lessons(teacher_id);

CREATE INDEX idx_lessons_subject_id
    ON lessons(subject_id);

CREATE INDEX idx_grades_student_id
    ON grades(student_id);

CREATE INDEX idx_grades_lesson_id
    ON grades(lesson_id);

CREATE INDEX idx_student_parents_parent_id
    ON student_parents(parent_id);


