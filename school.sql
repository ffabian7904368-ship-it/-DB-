INSERT INTO grades (student_id, lesson_id, grade_value, comment)
SELECT
    s.student_id,
    l.lesson_id,
    (3 + ((s.student_id + l.lesson_id) % 3))::SMALLINT AS grade_value,
    CASE
        WHEN (3 + ((s.student_id + l.lesson_id) % 3)) = 5
            THEN 'Отличная работа'
        WHEN (3 + ((s.student_id + l.lesson_id) % 3)) = 4
            THEN 'Хорошая работа'
        ELSE 'Нужно повторить тему'
    END AS comment
FROM students AS s
JOIN lessons AS l
    ON l.class_id = s.class_id
WHERE l.day_of_week = 'Понедельник'
  AND l.lesson_number IN (1, 2);



